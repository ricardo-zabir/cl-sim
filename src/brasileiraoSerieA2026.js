export function placarBraEhOficial(id) {
  return Object.prototype.hasOwnProperty.call(PLACARES_OFICIAIS_BRA, id);
}

export function jogosDaRodadaBra(rodada) {
  return JOGOS_BRA.filter((j) => j.rodada === rodada);
}

function linhaVazia(nome) {
  return {
    nome,
    pts: 0,
    j: 0,
    v: 0,
    e: 0,
    d: 0,
    gp: 0,
    gc: 0,
    sg: 0,
  };
}

/**
 * Classificação a partir dos placares preenchidos.
 * Critérios ao vivo CBF: pts → vitórias → SG → GP → nome.
 */
export function calcularTabelaBra(placares) {
  const mapa = Object.fromEntries(TIMES_BRA.map((n) => [n, linhaVazia(n)]));

  for (const jogo of JOGOS_BRA) {
    const p = placares[jogo.id];
    if (!p || p.casa == null || p.fora == null) continue;
    const casa = mapa[jogo.casa];
    const fora = mapa[jogo.fora];
    if (!casa || !fora) continue;

    casa.j += 1;
    fora.j += 1;
    casa.gp += p.casa;
    casa.gc += p.fora;
    fora.gp += p.fora;
    fora.gc += p.casa;
    casa.sg = casa.gp - casa.gc;
    fora.sg = fora.gp - fora.gc;

    if (p.casa > p.fora) {
      casa.v += 1;
      casa.pts += 3;
      fora.d += 1;
    } else if (p.casa < p.fora) {
      fora.v += 1;
      fora.pts += 3;
      casa.d += 1;
    } else {
      casa.e += 1;
      fora.e += 1;
      casa.pts += 1;
      fora.pts += 1;
    }
  }

  return Object.values(mapa).sort((a, b) => {
    if (b.pts !== a.pts) return b.pts - a.pts;
    if (b.v !== a.v) return b.v - a.v;
    if (b.sg !== a.sg) return b.sg - a.sg;
    if (b.gp !== a.gp) return b.gp - a.gp;
    return a.nome.localeCompare(b.nome, "pt");
  });
}

/** Zona: 1–4 Liberta, 5–6 Pré-Liberta, 7–12 Sula, 17–20 rebaixamento. */
export function zonaClassificacaoBra(pos) {
  if (pos <= 4) return "libertadores";
  if (pos <= 6) return "preLibertadores";
  if (pos <= 12) return "sulamericana";
  if (pos >= 17) return "rebaixamento";
  return "meio";
}
